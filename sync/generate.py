#!/usr/bin/env python3
"""Writes a network branch's tree from the network's on-chain package registry.

The tree holds the four framework packages published at 0x1, each with the
`Move.toml` and module sources stored in `0x1::code::PackageRegistry`, plus the
generated files listed in the repository README. The output depends only on the
registry and the chain ID, so an unchanged registry produces an unchanged tree.

Prints the tag name for the tree on stdout.
"""

import argparse
import gzip
import hashlib
import json
import os
import re
import shutil
import sys
import time
import urllib.request

NETWORKS = {
    "mainnet": ("https://rpc-mainnet.supra.com", 8),
    "testnet": ("https://rpc-testnet.supra.com", 6),
    "devnet": ("https://rpc-devnet.supra.com", 50),
}

# Package name and directory, in the order used to compute the tag name.
PACKAGES = (
    ("MoveStdlib", "move-stdlib"),
    ("AptosStdlib", "aptos-stdlib"),
    ("SupraStdlib", "supra-stdlib"),
    ("SupraFramework", "supra-framework"),
)

REGISTRY_PATH = "/rpc/v3/accounts/0x1/resources/0x1::code::PackageRegistry"
CHAIN_ID_PATH = "/rpc/v3/transactions/chain_id"
USER_AGENT = "supra-framework-sync (+https://github.com/Entropy-Foundation/supra-framework)"

STATIC_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "static")
UNIT_TEST_MODULE = "unit_test"

IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
TEST_ONLY_FRIEND = re.compile(r"#\[test_only\]\s*friend\s+(\w+)::(\w+)\s*;")

STUB_TEMPLATE = """\
// Generated by sync/generate.py. Placeholder for a test-only module that is not
// published on chain and is named by a `#[test_only] friend` declaration.
#[test_only]
module {address}::{name} {{}}
"""

BRANCH_README_TEMPLATE = """\
# Supra Framework: {title}

This branch holds the Move framework packages deployed at `0x1` on {title}
(chain ID {chain_id}), generated from the on-chain package registry.
`registry.json` records each package's upgrade number and source digest.

See the README on the `main` branch for usage, tags and the generated files.
"""


class RegistryError(Exception):
    pass


def fetch(url, attempts=3, timeout=30):
    # The RPC endpoints reject urllib's default User-Agent with 403.
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept": "application/json"})
    for attempt in range(1, attempts + 1):
        try:
            with urllib.request.urlopen(request, timeout=timeout) as response:
                return response.read()
        except OSError as error:
            if attempt == attempts:
                raise RegistryError(f"GET {url} failed: {error}") from error
            time.sleep(5 * attempt)


def gunzip_hex(value, what):
    if not isinstance(value, str) or not value.startswith("0x") or len(value) <= 2:
        raise RegistryError(f"{what} is empty or not a hex string")
    try:
        return gzip.decompress(bytes.fromhex(value[2:]))
    except (ValueError, OSError) as error:
        raise RegistryError(f"{what} is not gzipped hex: {error}") from error


def defines_module(source, name):
    return re.search(rf"^\s*module\s+\w+::{name}\b", source, re.MULTILINE) is not None


def parse_packages(registry):
    """Returns {package name: package} after checking the registry's shape."""
    try:
        packages = registry["data"]["packages"]
    except (KeyError, TypeError) as error:
        raise RegistryError("response has no data.packages") from error
    by_name = {}
    for package in packages:
        name = package.get("name")
        if name in by_name:
            raise RegistryError(f"package {name} appears twice")
        by_name[name] = package
    expected = {name for name, _ in PACKAGES}
    if set(by_name) != expected:
        raise RegistryError(
            f"registry holds {sorted(by_name, key=str)}, expected {sorted(expected)}"
        )
    return by_name


def clear(out_dir):
    """Removes everything in out_dir except `.git`."""
    os.makedirs(out_dir, exist_ok=True)
    for entry in os.listdir(out_dir):
        if entry == ".git":
            continue
        path = os.path.join(out_dir, entry)
        if os.path.isdir(path) and not os.path.islink(path):
            shutil.rmtree(path)
        else:
            os.remove(path)


def write(path, data):
    directory = os.path.dirname(path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    mode = "wb" if isinstance(data, bytes) else "w"
    with open(path, mode) as file:
        file.write(data)


def tag_name(network, packages):
    digests = "".join(packages[name]["source_digest"] for name, _ in PACKAGES)
    return f"{network}-{hashlib.sha256(digests.encode()).hexdigest()[:12]}"


def generate(network, registry, chain_id, out_dir):
    """Writes the tree for `registry` into out_dir and returns its tag name."""
    expected_chain_id = NETWORKS[network][1]
    if chain_id != expected_chain_id:
        raise RegistryError(f"chain ID is {chain_id}, expected {expected_chain_id}")
    packages = parse_packages(registry)

    clear(out_dir)
    summary = []
    for name, directory in PACKAGES:
        package = packages[name]
        digest = package.get("source_digest")
        if not isinstance(digest, str) or not re.fullmatch(r"[0-9A-Fa-f]{64}", digest):
            raise RegistryError(f"{name} has no valid source_digest")
        root = os.path.join(out_dir, directory)
        write(os.path.join(root, "Move.toml"), gunzip_hex(package.get("manifest"), f"{name} manifest"))

        sources = {}
        for module in package.get("modules", []):
            module_name = module.get("name")
            if not isinstance(module_name, str) or not IDENTIFIER.fullmatch(module_name):
                raise RegistryError(f"{name} has a module with an invalid name: {module_name!r}")
            if module_name in sources:
                raise RegistryError(f"{name} has module {module_name} twice")
            source = gunzip_hex(module.get("source"), f"{name}::{module_name} source")
            if not defines_module(source.decode(), module_name):
                raise RegistryError(f"{name}::{module_name} source does not define the module")
            sources[module_name] = source
        if not sources:
            raise RegistryError(f"{name} has no modules")
        for module_name, source in sources.items():
            write(os.path.join(root, "sources", f"{module_name}.move"), source)

        stubs = {}
        for source in sources.values():
            for address, friend in TEST_ONLY_FRIEND.findall(source.decode()):
                if friend not in sources:
                    stubs[friend] = address
        for friend, address in sorted(stubs.items()):
            write(
                os.path.join(root, "sources", f"{friend}.move"),
                STUB_TEMPLATE.format(address=address, name=friend),
            )

        if directory == "move-stdlib" and UNIT_TEST_MODULE not in sources:
            relative = os.path.join(directory, "sources", f"{UNIT_TEST_MODULE}.move")
            shutil.copyfile(os.path.join(STATIC_DIR, relative), os.path.join(out_dir, relative))

        summary.append(
            {"name": name, "upgrade_number": str(package.get("upgrade_number")), "source_digest": digest}
        )

    record = {"network": network, "chain_id": chain_id, "packages": summary}
    write(os.path.join(out_dir, "registry.json"), json.dumps(record, indent=2) + "\n")
    write(
        os.path.join(out_dir, "README.md"),
        BRANCH_README_TEMPLATE.format(title=network.capitalize(), chain_id=chain_id),
    )
    return tag_name(network, packages)


def commit_message(network, tag, out_dir):
    with open(os.path.join(out_dir, "registry.json")) as file:
        record = json.load(file)
    lines = [f"{network.capitalize()} framework as deployed at 0x1 ({tag})", ""]
    for package in record["packages"]:
        lines.append(
            f"{package['name']}: upgrade {package['upgrade_number']}, source digest {package['source_digest']}"
        )
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--network", required=True, choices=sorted(NETWORKS))
    parser.add_argument("--out", required=True, help="directory to write the tree into")
    parser.add_argument("--registry", help="read the registry from this JSON file instead of the RPC")
    parser.add_argument("--chain-id", type=int, help="chain ID to use with --registry")
    parser.add_argument("--message-file", help="write a commit message for the tree to this file")
    args = parser.parse_args(argv)

    rpc = NETWORKS[args.network][0]
    try:
        if args.registry:
            if args.chain_id is None:
                parser.error("--registry requires --chain-id")
            with open(args.registry, "rb") as file:
                registry = json.loads(file.read())
            chain_id = args.chain_id
        else:
            registry = json.loads(fetch(rpc + REGISTRY_PATH))
            chain_id = int(fetch(rpc + CHAIN_ID_PATH))
        tag = generate(args.network, registry, chain_id, args.out)
    except (RegistryError, ValueError) as error:
        print(f"error: {args.network}: {error}", file=sys.stderr)
        return 1
    if args.message_file:
        write(args.message_file, commit_message(args.network, tag, args.out))
    print(tag)
    return 0


if __name__ == "__main__":
    sys.exit(main())
