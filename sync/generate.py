#!/usr/bin/env python3
"""Writes a network branch's tree from the network's on-chain package registry.

The registry is `0x1::code::PackageRegistry`, read in its BCS encoding. The tree
holds the four framework packages published at 0x1, each with the `Move.toml` and
module sources stored in the registry, plus the generated files listed in the
repository README. The output depends only on the registry, the chain ID, the
genesis hash and this generator, so an unchanged registry produces an unchanged
tree.

Prints the tree's tag name on stdout: the network and the first 12 hex characters
of the SHA-256 of the registry's BCS encoding.

Exit status: 0 when the tree is written, 1 on an error, and 3 when the registry
changed between two reads, in which case nothing is written.
"""

import argparse
import gzip
import hashlib
import http.client
import json
import os
import re
import shutil
import sys
import time
import urllib.request

NETWORKS = {
    "mainnet": ("https://rpc-mainnet.supra.com", 8),
    "testnet": ("https://rpc-testnet.supra.com", 6),
    "devnet": ("https://rpc-devnet.supra.com", 50),
}

# Networks whose genesis may change. On any other network a changed genesis hash
# is an error.
RESETTABLE_NETWORKS = {"devnet"}

# Package name and directory, in the order the packages are recorded in registry.json.
PACKAGES = (
    ("MoveStdlib", "move-stdlib"),
    ("AptosStdlib", "aptos-stdlib"),
    ("SupraStdlib", "supra-stdlib"),
    ("SupraFramework", "supra-framework"),
)

REGISTRY_PATH = "/rpc/v3/accounts/0x1/resources/0x1::code::PackageRegistry"
GENESIS_COMMITTEE_PATH = "/rpc/v4/consensus/committees/0"
CHAIN_ID_HEADER = "x-supra-chain-id"
USER_AGENT = "supra-framework-sync (+https://github.com/Entropy-Foundation/supra-framework)"
TAG_HASH_LENGTH = 12

# A changed registry is read a second time after this many seconds, and is used
# only if both reads return the same bytes. A framework upgrade publishes its
# packages in separate transactions, so a single read can see part of one.
STABLE_READ_DELAY_SECONDS = 60
EXIT_UNSTABLE = 3

STATIC_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "static")
UNIT_TEST_MODULE = "unit_test"

IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
SOURCE_DIGEST = re.compile(r"[0-9A-Fa-f]{64}")
GENESIS_HASH = re.compile(r"0x[0-9a-f]{64}")
FRIEND = re.compile(r"((?:#\[[^\]]*\]\s*)+)friend\s+(\w+)::(\w+)\s*;")
ATTRIBUTE_LIST = re.compile(r"#\[([^\]]*)\]")

STUB_TEMPLATE = """\
// Generated by sync/generate.py. Placeholder for a test-only module that is not
// published on chain and is named by a `#[test_only] friend` declaration.
#[test_only]
module {address}::{name} {{}}
"""

BRANCH_README_TEMPLATE = """\
# Supra Framework: {title}

This branch holds the Move framework packages deployed at `0x1` on {title}
(chain ID {chain_id}), generated from the on-chain package registry.
`registry.json` records the network's genesis hash, the registry's SHA-256, and
each package's upgrade number and source digest.

See the README on the `main` branch for usage, tags and the generated files.
"""


class RegistryError(Exception):
    pass


class UnstableRegistry(Exception):
    pass


def fetch(url, accept, attempts=3, timeout=30):
    """Returns (body, headers) for a GET of url."""
    # The RPC endpoints reject urllib's default User-Agent with 403.
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept": accept})
    for attempt in range(1, attempts + 1):
        try:
            with urllib.request.urlopen(request, timeout=timeout) as response:
                content_type = response.headers.get_content_type()
                if content_type != accept:
                    raise RegistryError(f"GET {url} returned {content_type}, expected {accept}")
                return response.read(), response.headers
        except (OSError, http.client.HTTPException) as error:
            if attempt == attempts:
                raise RegistryError(f"GET {url} failed: {error}") from error
            time.sleep(5 * attempt)


class BcsReader:
    """Reads the BCS encoding of `vector<0x1::code::PackageMetadata>`."""

    def __init__(self, data):
        self.data = data
        self.offset = 0

    def take(self, length):
        end = self.offset + length
        if end > len(self.data):
            raise RegistryError(f"registry BCS ends at byte {len(self.data)}, expected {end}")
        value = self.data[self.offset:end]
        self.offset = end
        return value

    def uleb128(self):
        value = shift = 0
        while True:
            byte = self.take(1)[0]
            value |= (byte & 0x7F) << shift
            if byte < 0x80:
                return value
            shift += 7
            if shift > 63:
                raise RegistryError("registry BCS has an over-long length")

    def u8(self):
        return self.take(1)[0]

    def u64(self):
        return int.from_bytes(self.take(8), "little")

    def bytes(self):
        return self.take(self.uleb128())

    def string(self):
        try:
            return self.bytes().decode("utf-8")
        except UnicodeDecodeError as error:
            raise RegistryError(f"registry BCS has a string that is not UTF-8: {error}") from error

    def vector(self, read):
        return [read() for _ in range(self.uleb128())]

    def option_any(self):
        """Reads `Option<0x1::copyable_any::Any>`: a type name and BCS bytes."""
        flag = self.u8()
        if flag == 0:
            return None
        if flag != 1:
            raise RegistryError(f"registry BCS has an option flag of {flag}")
        return (self.string(), self.bytes())

    def module(self):
        return {
            "name": self.string(),
            "source": self.bytes(),
            "source_map": self.bytes(),
            "extension": self.option_any(),
        }

    def dependency(self):
        return {"account": self.take(32), "package_name": self.string()}

    def package(self):
        return {
            "name": self.string(),
            "upgrade_policy": self.u8(),
            "upgrade_number": self.u64(),
            "source_digest": self.string(),
            "manifest": self.bytes(),
            "modules": self.vector(self.module),
            "deps": self.vector(self.dependency),
            "extension": self.option_any(),
        }


def parse_registry(data):
    """Returns {package name: package} from the registry's BCS encoding."""
    reader = BcsReader(data)
    packages = reader.vector(reader.package)
    if reader.offset != len(data):
        raise RegistryError(f"registry BCS has {len(data) - reader.offset} bytes after the packages")
    by_name = {}
    for package in packages:
        if package["name"] in by_name:
            raise RegistryError(f"package {package['name']} appears twice")
        by_name[package["name"]] = package
    expected = {name for name, _ in PACKAGES}
    if set(by_name) != expected:
        raise RegistryError(f"registry holds {sorted(by_name)}, expected {sorted(expected)}")
    return by_name


def parse_genesis_hash(body, chain_id):
    """Returns the hash certified for epoch 0 by the genesis committee.

    The hash is the digest of the network's genesis configuration.
    """
    try:
        committee = json.loads(body)
        (version,) = committee.values()
        data = version["authorization"]["certificate"]["data"]
        epoch_id, genesis_hash = data["epoch_id"], data["hash"]
    except (ValueError, TypeError, KeyError, AttributeError) as error:
        raise RegistryError(f"genesis committee response has an unexpected shape: {error!r}") from error
    if epoch_id.get("epoch") != 0 or epoch_id.get("chain_id") != chain_id:
        raise RegistryError(f"genesis committee is for {epoch_id}, expected epoch 0 of chain {chain_id}")
    if not isinstance(genesis_hash, str) or not GENESIS_HASH.fullmatch(genesis_hash):
        raise RegistryError(f"genesis committee has an invalid hash: {genesis_hash!r}")
    return genesis_hash


def read_network(network, previous, fetch=fetch, sleep=time.sleep):
    """Returns (registry_bcs, chain_id, genesis_hash) read from the network's RPC.

    A registry whose SHA-256 differs from `previous` is read again after
    STABLE_READ_DELAY_SECONDS; UnstableRegistry is raised if the two reads differ.
    """
    rpc, expected_chain_id = NETWORKS[network]
    registry_bcs, headers = fetch(rpc + REGISTRY_PATH, "application/x-bcs")
    try:
        chain_id = int(headers.get(CHAIN_ID_HEADER, ""))
    except ValueError as error:
        raise RegistryError(f"registry response has no valid {CHAIN_ID_HEADER} header") from error
    if chain_id != expected_chain_id:
        raise RegistryError(f"chain ID is {chain_id}, expected {expected_chain_id}")
    if previous is None or previous.get("registry_sha256") != hashlib.sha256(registry_bcs).hexdigest():
        sleep(STABLE_READ_DELAY_SECONDS)
        second, _ = fetch(rpc + REGISTRY_PATH, "application/x-bcs")
        if second != registry_bcs:
            raise UnstableRegistry(f"the registry changed within {STABLE_READ_DELAY_SECONDS} seconds")
    committee, _ = fetch(rpc + GENESIS_COMMITTEE_PATH, "application/json")
    return registry_bcs, chain_id, parse_genesis_hash(committee, chain_id)


def check_history(network, previous, genesis_hash, packages):
    """Returns "new", "continue" or "reset" for a registry against the branch head's registry.json.

    `previous` is the branch head's registry.json, or None for a new branch.
    Raises RegistryError for a changed genesis on a network that is not
    resettable, and for a registry that is older than the branch head: no
    package's upgrade number is higher and at least one is lower.
    """
    if previous is None:
        return "new"
    previous_genesis = previous.get("genesis_hash")
    if not previous_genesis:
        raise RegistryError("the branch head's registry.json has no genesis_hash")
    if previous_genesis != genesis_hash:
        if network not in RESETTABLE_NETWORKS:
            raise RegistryError(f"genesis hash changed from {previous_genesis} to {genesis_hash}")
        return "reset"
    before = {p["name"]: int(p["upgrade_number"]) for p in previous.get("packages", [])}
    pairs = [(packages[name]["upgrade_number"], before[name]) for name, _ in PACKAGES if name in before]
    if pairs and all(now <= then for now, then in pairs) and any(now < then for now, then in pairs):
        raise RegistryError(
            "the registry is older than the branch head: "
            + ", ".join(f"{name} {before.get(name)} -> {packages[name]['upgrade_number']}" for name, _ in PACKAGES)
        )
    return "continue"


def gunzip(data, what):
    if not data:
        raise RegistryError(f"{what} is empty")
    try:
        return gzip.decompress(data)
    except (OSError, EOFError) as error:
        raise RegistryError(f"{what} is not gzipped: {error}") from error


def code_only(source):
    """Returns `source` with comments and string literals replaced by spaces.

    Block comments nest, as in the Move lexer.
    """
    out = []
    i, n = 0, len(source)
    while i < n:
        if source.startswith("//", i):
            end = source.find("\n", i)
            end = n if end == -1 else end
            out.append(" " * (end - i))
            i = end
        elif source.startswith("/*", i):
            depth, j = 1, i + 2
            while j < n and depth:
                if source.startswith("/*", j):
                    depth, j = depth + 1, j + 2
                elif source.startswith("*/", j):
                    depth, j = depth - 1, j + 2
                else:
                    j += 1
            out.append(re.sub(r"[^\n]", " ", source[i:j]))
            i = j
        elif source[i] == '"':
            j = i + 1
            while j < n and source[j] != '"':
                j += 2 if source[j] == "\\" else 1
            j = min(j + 1, n)
            out.append(re.sub(r"[^\n]", " ", source[i:j]))
            i = j
        else:
            out.append(source[i])
            i += 1
    return "".join(out)


def test_only_friends(source):
    """Returns (address, module) for each `friend` declaration with a `test_only` attribute."""
    friends = []
    for attributes, address, name in FRIEND.findall(code_only(source)):
        names = {
            attribute.split("(")[0].strip()
            for attribute_list in ATTRIBUTE_LIST.findall(attributes)
            for attribute in attribute_list.split(",")
        }
        if "test_only" in names:
            friends.append((address, name))
    return friends


def defines_module(source, name):
    """True if the source declares the module, as `module addr::name {` or `module name {`."""
    return re.search(rf"\bmodule\s+(?:\w+::)?{name}\s*\{{", code_only(source)) is not None


def clear(out_dir):
    """Removes everything in out_dir except `.git`."""
    os.makedirs(out_dir, exist_ok=True)
    for entry in os.listdir(out_dir):
        if entry == ".git":
            continue
        path = os.path.join(out_dir, entry)
        if os.path.isdir(path) and not os.path.islink(path):
            shutil.rmtree(path)
        else:
            os.remove(path)


def write(path, data):
    directory = os.path.dirname(path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    mode = "wb" if isinstance(data, bytes) else "w"
    with open(path, mode) as file:
        file.write(data)


def tag_name(network, registry_bcs):
    return f"{network}-{hashlib.sha256(registry_bcs).hexdigest()[:TAG_HASH_LENGTH]}"


def module_sources(packages):
    """Returns {package name: {module name: (bytes, text)}} after checking each module."""
    result = {}
    for name, _ in PACKAGES:
        package = packages[name]
        if not SOURCE_DIGEST.fullmatch(package["source_digest"]):
            raise RegistryError(f"{name} has no valid source_digest")
        sources = {}
        for module in package["modules"]:
            module_name = module["name"]
            if not IDENTIFIER.fullmatch(module_name):
                raise RegistryError(f"{name} has a module with an invalid name: {module_name!r}")
            if module_name in sources:
                raise RegistryError(f"{name} has module {module_name} twice")
            source = gunzip(module["source"], f"{name}::{module_name} source")
            try:
                text = source.decode("utf-8")
            except UnicodeDecodeError as error:
                raise RegistryError(f"{name}::{module_name} source is not UTF-8") from error
            if not defines_module(text, module_name):
                raise RegistryError(f"{name}::{module_name} source does not define the module")
            sources[module_name] = (source, text)
        if not sources:
            raise RegistryError(f"{name} has no modules")
        result[name] = sources
    return result


def generate(network, registry_bcs, chain_id, genesis_hash, out_dir):
    """Writes the tree for the registry into out_dir and returns its tag name."""
    expected_chain_id = NETWORKS[network][1]
    if chain_id != expected_chain_id:
        raise RegistryError(f"chain ID is {chain_id}, expected {expected_chain_id}")
    if not GENESIS_HASH.fullmatch(genesis_hash):
        raise RegistryError(f"invalid genesis hash: {genesis_hash!r}")
    packages = parse_registry(registry_bcs)
    sources = module_sources(packages)
    # All four packages publish at 0x1, so a friend in any of them is on chain.
    on_chain = {module for package in sources.values() for module in package}

    clear(out_dir)
    summary = []
    for name, directory in PACKAGES:
        package = packages[name]
        root = os.path.join(out_dir, directory)
        write(os.path.join(root, "Move.toml"), gunzip(package["manifest"], f"{name} manifest"))
        for module_name, (source, _) in sources[name].items():
            write(os.path.join(root, "sources", f"{module_name}.move"), source)

        stubs = {}
        for _, text in sources[name].values():
            for address, friend in test_only_friends(text):
                if friend not in on_chain:
                    stubs[friend] = address
        for friend, address in sorted(stubs.items()):
            write(
                os.path.join(root, "sources", f"{friend}.move"),
                STUB_TEMPLATE.format(address=address, name=friend),
            )

        if directory == "move-stdlib" and UNIT_TEST_MODULE not in on_chain:
            relative = os.path.join(directory, "sources", f"{UNIT_TEST_MODULE}.move")
            shutil.copyfile(os.path.join(STATIC_DIR, relative), os.path.join(out_dir, relative))

        summary.append(
            {
                "name": name,
                "upgrade_number": str(package["upgrade_number"]),
                "source_digest": package["source_digest"],
            }
        )

    record = {
        "network": network,
        "chain_id": chain_id,
        "genesis_hash": genesis_hash,
        "registry_sha256": hashlib.sha256(registry_bcs).hexdigest(),
        "packages": summary,
    }
    write(os.path.join(out_dir, "registry.json"), json.dumps(record, indent=2) + "\n")
    write(
        os.path.join(out_dir, "README.md"),
        BRANCH_README_TEMPLATE.format(title=network.capitalize(), chain_id=chain_id),
    )
    return tag_name(network, registry_bcs)


def commit_message(network, tag, history, previous, out_dir):
    with open(os.path.join(out_dir, "registry.json")) as file:
        record = json.load(file)
    lines = [f"{network.capitalize()} framework as deployed at 0x1 ({tag})", ""]
    if history == "reset":
        lines += [f"{network.capitalize()} was reset: genesis hash {previous['genesis_hash']} is now "
                  f"{record['genesis_hash']}.", ""]
    lines += [f"Genesis hash: {record['genesis_hash']}", f"Registry SHA-256: {record['registry_sha256']}"]
    for package in record["packages"]:
        lines.append(
            f"{package['name']}: upgrade {package['upgrade_number']}, source digest {package['source_digest']}"
        )
    return "\n".join(lines) + "\n"


def load_previous(path):
    if not path or not os.path.exists(path):
        return None
    try:
        with open(path) as file:
            return json.load(file)
    except ValueError as error:
        raise RegistryError(f"{path} is not valid JSON: {error}") from error


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--network", required=True, choices=sorted(NETWORKS))
    parser.add_argument("--out", required=True, help="directory to write the tree into")
    parser.add_argument("--previous", help="the branch head's registry.json; absent for a new branch")
    parser.add_argument("--registry", help="read the registry's BCS encoding from this file instead of the RPC")
    parser.add_argument("--chain-id", type=int, help="chain ID to use with --registry")
    parser.add_argument("--genesis-hash", help="genesis hash to use with --registry")
    parser.add_argument("--message-file", help="write a commit message for the tree to this file")
    args = parser.parse_args(argv)

    try:
        previous = load_previous(args.previous)
        if args.registry:
            if args.chain_id is None or args.genesis_hash is None:
                parser.error("--registry requires --chain-id and --genesis-hash")
            with open(args.registry, "rb") as file:
                registry_bcs = file.read()
            chain_id, genesis_hash = args.chain_id, args.genesis_hash
        else:
            registry_bcs, chain_id, genesis_hash = read_network(args.network, previous)
        history = check_history(args.network, previous, genesis_hash, parse_registry(registry_bcs))
        tag = generate(args.network, registry_bcs, chain_id, genesis_hash, args.out)
    except UnstableRegistry as error:
        print(f"warning: {args.network}: {error}; nothing written", file=sys.stderr)
        return EXIT_UNSTABLE
    except (RegistryError, ValueError) as error:
        print(f"error: {args.network}: {error}", file=sys.stderr)
        return 1
    if history == "reset":
        print(f"{args.network} was reset; genesis hash is now {genesis_hash}", file=sys.stderr)
    if args.message_file:
        write(args.message_file, commit_message(args.network, tag, history, previous, args.out))
    print(tag)
    return 0


if __name__ == "__main__":
    sys.exit(main())
